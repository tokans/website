#!/usr/bin/env node
/**
 * Codegen: inline the hand-editable HTML partials into a JS module so the
 * BUILDLESS static pages can inject them SYNCHRONOUSLY (no flash, and no runtime
 * fetch — a live fetch of /partials/*.html breaks under `vercel dev` because
 * cleanUrls 308-redirects the `.html` URL to an extensionless path that 404s).
 *
 * Reads  public/partials/header-prelogin.html  → export `headerPrelogin`
 *        public/partials/footer.html           → export `footer`
 * Writes public/js/partials.generated.js  (ES module, imported by public/js/chrome.js)
 *
 * The React app reads the SAME source partials directly via Vite `?raw`. Re-run
 * after editing a partial:  npm run build:partials  (also runs via `prelocal` /
 * `build`; in Vite dev the React side hot-reloads `?raw` edits automatically).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
// Drop the leading editor-facing HTML comment so it doesn't ship in the markup.
const stripLeadingComment = (html) => html.replace(/^\s*<!--[\s\S]*?-->\s*/, "");
const read = (rel) => stripLeadingComment(readFileSync(resolve(root, rel), "utf8")).trim();

const headerPrelogin = read("public/partials/header-prelogin.html");
const footer = read("public/partials/footer.html");

const out = `// AUTO-GENERATED by scripts/build-partials.mjs - DO NOT EDIT.
// Edit the source partials in public/partials/ and re-run \`npm run build:partials\`.
// This module exists so the buildless static pages can inject chrome synchronously.
export const headerPrelogin = ${JSON.stringify(headerPrelogin)};
export const footer = ${JSON.stringify(footer)};
`;

const outPath = resolve(root, "public/js/partials.generated.js");
writeFileSync(outPath, out);
console.log(
  `✓ generated public/js/partials.generated.js ` +
    `(header ${headerPrelogin.length}B, footer ${footer.length}B)`,
);
